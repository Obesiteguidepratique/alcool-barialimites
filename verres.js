function _volAutorise(c) {
  // Volume max pour cette boisson compte tenu du taux résiduel des AUTRES consommations
  var b = boissons[c.boissonIdx];
  var deg = b.autre ? (c.degreCustom || 0) : (b.degre || 0);
  if (deg === 0) return c.vol;
  var poids2 = getPoidsKg() || 80;
  var muscle2 = parseFloat(document.getElementById('muscle').value) || 10;
  var coeff2 = genre === 'homme' ? 0.68 : 0.55;
  var {cf: cf2, ef: ef2} = getChirFactors();
  var coeffAj2 = coeff2 * (1 + 0.3*(muscle2/poids2)) * cf2;
  var elim2 = genre === 'homme' ? 0.12 : 0.10;
  var elimAj2 = elim2 * ef2;
  // Taux résiduel des AUTRES consos (exclut c) à l'heure de cette conso
  var delai2 = getDelaiAbsorption();
  var tauxRes = 0;
  session.forEach(function(o) {
    if (o.id === c.id) return; // exclure la conso visée elle-même
    var bo = boissons[o.boissonIdx];
    var degO = bo.autre ? (o.degreCustom||0) : bo.degre;
    var afO = o.alimentaire === 'jeun' ? 1.15 : 1.0;
    var alcO = o.vol * o.nbVerres * (degO/100) * 0.789 * afO;
    var t0O = alcO / (poids2 * coeffAj2 * 1000) * 1000;
    var hPicO = o.heureDecimal + delai2;
    var durO = c.heureDecimal - hPicO;
    if (c.heureDecimal < o.heureDecimal) return;
    if (durO < 0) tauxRes += t0O * (c.heureDecimal - o.heureDecimal) / delai2;
    else tauxRes += Math.max(0, t0O - elimAj2 * durO);
  });
  var seuilBari2 = getSeuilBari();
  var margeG = Math.max(0, (seuilBari2 * 0.95 - tauxRes) * poids2 * coeffAj2);
  return Math.round(margeG / ((deg/100) * 0.789));
}

function _renderVisuVerre() {
  var c = _visuConsoId !== null ? session.find(function(x){ return x.id === _visuConsoId; }) : null;
  if (!c) return;
  var b = boissons[c.boissonIdx];
  var s = Object.assign({}, _formes[_visuForme] || _formes.vin, {_key: _visuForme || 'vin'});
  // build 413 : pour une consommation déjà confirmée dans la session, on affiche son volume
  // réellement prévu (c.vol), pas une marge "combien encore" recalculée — _volAutorise répondait
  // à une question différente (combien ajouter MAINTENANT), sans rapport avec un plan déjà acté
  // (ex. une dose issue d'une répartition autour d'un repas).
  // build 494 : si "Répartir" ou "Étaler", volTotal = somme du groupe
  var volTotal = c.vol;
  if (c.splitId) {
    volTotal = session.reduce(function(sum, o) {
      return (o.splitId === c.splitId) ? sum + o.vol : sum;
    }, 0);
  } else if (c.etalerId) {
    volTotal = session.reduce(function(sum,o){return(o.etalerId===c.etalerId)?sum+o.vol:sum;},0);
  } else if (c.gorgeeId) {
    volTotal = session.reduce(function(sum,o){return(o.gorgeeId===c.gorgeeId)?sum+o.vol:sum;},0);
  }
  // build 496 : split → volTotal directement (autoThrottle a déjà validé la répartition)
  //             prise unique → cap par _volAutorise (limite bariatrique)
  //             build 533 : etalerId → même traitement que splitId
  var _round5 = function(v) { return Math.round(v / 5) * 5; };
  var volAuth = (c.splitId || c.etalerId || c.gorgeeId)
    ? _round5(volTotal)
    : _round5(Math.min(c.vol, _volAutorise(c)));
  var verreParDefaut = _formeDefaut(b);
  var estVerreDefaut = (_visuForme === verreParDefaut);
  // build 483 — Règle 3 : Restaurant si defVol du verre = defVol du standard
  var fActif483 = _formes[_visuForme];
  var fDefaut483 = _formes[verreParDefaut];
  var canResto483 = fActif483 && fDefaut483 && (fActif483.defVol === fDefaut483.defVol);
  var defLaisser = Math.max(0, s.defVol - volAuth);

  document.getElementById('visuVerreTitle').textContent = b.nom;

  // build 481 : display du bouton Restaurant géré par _updateBtnRestoState (pas ici)

  var svg = document.getElementById('visuVerre');
  var info = document.getElementById('visuVerreInfo');

  // build 471 : subtitle supprimé

  var rAuth = Math.min(volAuth / s.defVol, 1.0) * s.maxFill;

  if (_visuMode === 'restaurant') {
    // Le verre arrive plein. On montre la zone ROUGE en haut = ce qu'il NE FAUT PAS boire.
    var rLaisser = canResto483 ? Math.min(defLaisser / s.defVol, 1.0) * s.maxFill : 0;
    svg.innerHTML = _drawGlassResto(s, rAuth, rLaisser, canResto483, Math.round(defLaisser));
    info.textContent = !canResto483 ? 'Ce verre n’est pas conforme au standard.' : '';
  } else {
    // On verse soi-même jusqu'au niveau autorisé : zone ORANGE depuis le bas = ce qu'on peut boire.
    svg.innerHTML = _drawGlassAmis(s, rAuth, volAuth);
    info.textContent = '';
  }
}

